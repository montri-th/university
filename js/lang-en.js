const N = '([\\d,]+)';
const re = source => new RegExp(`^${source}$`);
const plural = (t, n, one, many) => `${n} ${t.plural(n, one, many)}`;
const students = (t, n) => plural(t, n, 'student', 'students');
const units = (t, n) => plural(t, n, 'reporting unit', 'reporting units');
/** "N คน" or "N หน่วย" (a measure's unit after its number) → English. */
const unitOf = (t, n, unit) => (unit === 'คน' ? students(t, n) : units(t, n));
const U = '(คน|หน่วย)';
const SUBJECT = '(นักศึกษา|หน่วยรายงาน)';
const subject = th => ({'นักศึกษา': 'students', 'หน่วยรายงาน': 'reporting units'}[th]);
/** A tile's label under its number: "77 provinces", "1 province". */
const count = (one, many) => (el, t) => t.plural(el.previousElementSibling?.textContent, one, many);
const bold = (one, many) => (el, t) => t.plural(el.querySelector('strong')?.textContent, one, many);
/** A semester as the student file labels it (“2568/2”, พ.ศ.) → “semester 2/2025” (ค.ศ. in English, §5.8). */
const term = (t, label) => { const m = /^(25\d\d)\/(\d)$/.exec(label); return m ? `semester ${m[2]}/${t.date(m[1])}` : t.date(label); };

